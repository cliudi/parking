const assert=require('node:assert/strict');
const {server,fakeMapRuntime}=require('./test-street-ui');
const {chromium}=require(process.env.PARKY_PLAYWRIGHT_MODULE||'playwright');
(async()=>{
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const origin='http://127.0.0.1:'+server.address().port;
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  try{
    const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.clock.install();
    await page.route('**/*',r=>r.request().url().startsWith(origin)?r.continue():r.fulfill({status:200,contentType:'application/json',body:'[]'}));
    await page.addInitScript(fakeMapRuntime);
    await page.addInitScript(()=>{
      localStorage.setItem('parkly-lastpos',JSON.stringify({lat:41,lng:69,acc:10,ts:Date.now()}));
      window.geoRequests=[];window.geoWatches=[];
      navigator.geolocation.getCurrentPosition=(success,error,options)=>geoRequests.push({success,error,options});
      navigator.geolocation.watchPosition=(success,error,options)=>{geoWatches.push({success,error,options});return geoWatches.length};
      navigator.geolocation.clearWatch=()=>{};
      window.fix=(lat,acc,age=0)=>({timestamp:Date.now()-age,coords:{latitude:lat,longitude:69.2,accuracy:acc}});
    });
    await page.goto(origin+'/index.html');
    assert.equal(await page.evaluate(()=>mePos),null);
    await page.evaluate(()=>{window.requestDone=centerOnMyLocation()});
    assert.equal(await page.evaluate(()=>geoRequests.length),2,'Requests start together');
    assert.equal(await page.evaluate(()=>geoWatches.length),1);
    await page.evaluate(()=>geoRequests[0].error({code:3}));
    await page.evaluate(()=>geoWatches[0].success(fix(41.3,25)));
    assert.equal(await page.evaluate(()=>mePos.lat),41.3,'Watch survives quick timeout');
    await page.evaluate(()=>geoRequests[1].success(fix(41.4,1000)));
    assert.equal(await page.evaluate(()=>mePos.lat),41.3,'Reject late coarse answer');
    await page.clock.runFor(76000);
    assert.equal(await page.evaluate(()=>ParkyLocation.origin()),null);
    assert.match(await page.locator('#locationStatus').textContent(),/Последнее известное/);
    await page.evaluate(()=>{window.requestDone=centerOnMyLocation()});
    await page.evaluate(()=>{geoRequests[2].error({code:3});geoRequests[3].error({code:3})});
    await page.clock.runFor(23000);
    assert.equal(await page.evaluate(()=>mePos.lat),41.3,'Retain stale point on timeout');
    assert.match(await page.locator('#locationStatus').textContent(),/Не удалось уточнить/);
    await page.evaluate(()=>{window.requestDone=centerOnMyLocation();geoRequests[4].success(fix(41.31,4000))});
    assert.match(await page.locator('#locationStatus').textContent(),/Приблизительное/);
    assert.equal(await page.evaluate(()=>ParkyLocation.origin()),null);
    await page.evaluate(()=>ParkyLocation.manual({lat:41.32,lng:69.21}));
    await page.evaluate(()=>geoRequests[5].success(fix(41.5,10)));
    assert.equal(await page.evaluate(()=>mePos.lat),41.32,'Manual point survives late callback');
    assert.match(await page.locator('#locationStatus').textContent(),/вручную/);
    assert.equal(await page.evaluate(()=>ParkyLocation.accuracy()),'Место указано вручную');
    assert.equal(await page.evaluate(()=>new URL(navigationUrl('google',{lat:41.4,lng:69.3})).searchParams.get('origin')),'41.320000,69.210000');
    await page.evaluate(()=>{window.requestDone=centerOnMyLocation();geoRequests[6].error({code:1})});
    assert.match(await page.locator('#locationStatus').textContent(),/Нет доступа/);
    await page.evaluate(()=>{document.getElementById('onboarding').classList.remove('on');document.getElementById('brandSplash')?.remove()});
    await page.evaluate(()=>{
      ymaps.templateLayoutFactory={createClass:s=>s};
      ymaps.Circle=class extends ymaps.Placemark{constructor(...args){super(...args);this.geometry.setRadius=()=>{}}};
      initMap();
    });
    await page.locator('#manualLocationButton').click({force:true});
    assert.equal(await page.evaluate(()=>ParkyLocation.picking()),true);
    await page.evaluate(()=>setSelectedPoint([41.33,69.22],'Test map point'));
    await page.getByRole('button',{name:'Я здесь — использовать как моё место',exact:true}).click({force:true});
    assert.equal(await page.evaluate(()=>ParkyLocation.origin().lat),41.33,'Map card confirmation sets manual origin');
    await page.clock.runFor(100);
    await page.screenshot({path:'release/location-mobile.png'});
    assert.deepEqual(errors,[]);
    console.log('Location: parallel providers, quality races, stale/denied/timeout, manual protection and navigation passed');
  }finally{await browser.close();server.close()}
})().catch(e=>{console.error(e);process.exitCode=1;server.close()});
