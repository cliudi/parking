const assert=require('node:assert/strict'),fs=require('node:fs');
const path=require('node:path'),root=fs.existsSync(path.join(__dirname,'../www/index.html'))?'../www/':'../';
const {chains,streetKey}=require(root+'assets/ready-parking-lines');
const p=(id,n,status='APPROVED',address='улица Навои, '+id)=>({id,lat:41.3+n*.001,lng:69.2,status,address,category:'OFFICIAL'});
const input=[p('a',0),p('b',1),p('c',2)],before=JSON.stringify(input);
assert.equal(streetKey('Ташкент, ул. Навои, 12'),streetKey('улица Навои 20'));
assert.equal(streetKey('Юнусабад, 16-й квартал, 28А'),'');
assert.equal(streetKey('улица 8'),'','Ambiguous numeric-only street must not collapse to a shared key');
assert.equal(streetKey('улица Навои, улица Пушкина'),'','Ambiguous intersection is not a street match');
assert.equal(chains(input).length,1);assert.equal(chains(input)[0].pointCount,3);
assert.equal(chains(input.slice(0,2)).length,0,'Two points are not a chain');
assert.equal(chains([...input,{...p('d',1.5),address:'улица Пушкина, 1'}])[0].pointCount,3);
assert.equal(chains([p('a',0),p('b',1,'DRAFT'),p('c',2),p('d',3)]).length,0,'Unfinished middle breaks sequence');
assert.equal(chains([p('a',0),p('b',1),p('c',2),p('d',6),p('e',7),p('f',8)]).length,2,'Do not bridge long gaps');
assert.equal(chains([p('a',0),p('b',.01),p('c',.02)]).length,0,'Duplicates are not three separate parking places');
assert.equal(chains([...input,p('duplicate-draft',1.01,'DRAFT')]).length,0,'Unfinished duplicate blocks completion');
assert.equal(chains(input.map(p=>({...p,address:''}))).length,0,'No guessed street from spatial proximity');
assert.equal(chains([...input,p('unknown-draft',1.5,'DRAFT','')]).length,0,'Nearby unfinished point with missing address is a conservative break');
assert.equal(chains(input.map(p=>({...p,category:'STREET_ALLOWED'}))).length,0,'Existing street geometry remains separate');
assert.equal(chains(input.map(p=>({...p,lat:null}))).length,0);
assert.equal(chains(input,[{status:'recheck',path:[[41.3008,69.2],[41.3012,69.2]]}]).length,0,'Manual not-done wins');
assert.equal(chains(input,[{status:'parking_added',checked_on:'2026-09-28',path:[[41.3,69.2],[41.302,69.2]]}]).length,0,'No dark double overlay over surveyed line');
assert.equal(chains([p('a',0),p('b',1),{...p('c',1),lng:69.202}]).length,0,'No sharp corner guessed between dots');
assert.equal(JSON.stringify(input),before,'No data writes or mutation');
assert(!fs.readFileSync(path.join(__dirname,root,'index.html'),'utf8').includes('ready-parking-lines'),'Admin only');
console.log('Ready chains: 3+, same street, gaps, draft breaks, duplicates, manual overrides, sharp turns and admin isolation OK');
